-- TOPZY initial Supabase schema.
-- Review and run in Supabase SQL Editor. Auth passwords remain in Supabase Auth.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('customer','owner','support')),
  created_at timestamptz not null default now()
);

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  currency text not null,
  icon_url text,
  status text not null default 'planned' check (status in ('planned','active','paused')),
  created_at timestamptz not null default now()
);

create table if not exists public.game_fields (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  field_key text not null,
  label text not null,
  required boolean not null default true,
  unique(game_id, field_key)
);

create table if not exists public.game_packages (
  id uuid primary key default gen_random_uuid(),
  game_id bigint not null references public.games(id) on delete cascade,
  package_name text not null,
  amount_label text,
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  status text not null default 'inactive' check (status in ('active','inactive','degraded','disabled')),
  created_at timestamptz not null default now()
);

create table if not exists public.supplier_products (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid not null references public.suppliers(id),
  package_id uuid not null references public.game_packages(id),
  external_product_id text not null,
  active boolean not null default false,
  unique(supplier_id, external_product_id),
  unique(supplier_id, package_id)
);

create table if not exists public.supplier_prices (
  id uuid primary key default gen_random_uuid(),
  supplier_product_id uuid not null references public.supplier_products(id),
  cost_minor bigint not null check (cost_minor >= 0),
  currency char(3) not null default 'NGN',
  checked_at timestamptz not null default now()
);

create table if not exists public.profit_tiers (
  id bigint generated by default as identity primary key,
  min_cost_minor bigint not null check (min_cost_minor >= 0),
  max_cost_minor bigint,
  profit_minor bigint not null check (profit_minor >= 0),
  active boolean not null default true,
  check (max_cost_minor is null or max_cost_minor >= min_cost_minor)
);

create table if not exists public.price_snapshots (
  id uuid primary key default gen_random_uuid(),
  package_id uuid not null references public.game_packages(id),
  supplier_product_id uuid not null references public.supplier_products(id),
  supplier_cost_minor bigint not null,
  selling_price_minor bigint not null,
  currency char(3) not null default 'NGN',
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  status text not null default 'pending_payment',
  total_minor bigint not null check (total_minor >= 0),
  currency char(3) not null default 'NGN',
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  package_id uuid not null references public.game_packages(id),
  quantity integer not null default 1 check (quantity > 0),
  unit_price_minor bigint not null check (unit_price_minor >= 0)
);

create table if not exists public.player_details (
  id uuid primary key default gen_random_uuid(),
  order_item_id uuid not null references public.order_items(id) on delete cascade,
  field_key text not null,
  field_value text not null
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id),
  provider text not null,
  provider_reference text not null unique,
  amount_minor bigint not null check (amount_minor >= 0),
  currency char(3) not null default 'NGN',
  status text not null default 'pending',
  verified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.payment_webhooks (
  id uuid primary key default gen_random_uuid(),
  provider_event_id text not null unique,
  event_type text not null,
  processed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.supplier_transactions (
  id uuid primary key default gen_random_uuid(),
  order_item_id uuid not null references public.order_items(id),
  supplier_id uuid not null references public.suppliers(id),
  external_order_id text unique,
  status text not null default 'queued',
  request_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance_minor bigint not null default 0 check (balance_minor >= 0),
  currency char(3) not null default 'NGN',
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  transaction_type text not null check (transaction_type in ('credit','debit','refund','adjustment')),
  amount_minor bigint not null check (amount_minor > 0),
  reference text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.refunds (
  id uuid primary key default gen_random_uuid(),
  payment_id uuid references public.payments(id),
  order_id uuid not null references public.orders(id),
  amount_minor bigint not null check (amount_minor > 0),
  status text not null default 'pending',
  provider_reference text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  subject text not null,
  status text not null default 'open',
  created_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  sender_id uuid not null references auth.users(id),
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id uuid primary key default gen_random_uuid(),
  admin_id uuid references auth.users(id),
  action text not null,
  target_type text,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.idempotency_keys (
  key text primary key,
  scope text not null,
  response jsonb,
  created_at timestamptz not null default now()
);

